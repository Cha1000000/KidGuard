package ru.homelab.kidguard.platform.notification

/**
 * Единый реестр id уведомлений приложения.
 *
 * Заведён по следам живого бага: предупреждение «Скоро время сна» и foreground-уведомление
 * VPN-сервиса независимо друг от друга выбрали себе id = 3. Предупреждение затирало VPN, а
 * снять его потом было невозможно — система не даёт отменить уведомление живого
 * foreground-сервиса, и оно висело в шторке до перезапуска приложения.
 *
 * Новый id добавляем ТОЛЬКО сюда, следующим числом, и никогда не переиспользуем чужой.
 */
object NotificationIds {

    /** Постоянное уведомление сервиса контроля (`KidGuardForegroundService`). */
    const val FOREGROUND_SERVICE = 1

    /** Предупреждение «осталось N минут» до конца дневного лимита. */
    const val LIMIT_WARNING = 2

    /** Foreground-уведомление VPN-сервиса (`KidGuardVpnService`). */
    const val VPN_SERVICE = 3

    /** Предупреждение «через N минут — Время сна». */
    const val SLEEP_WARNING = 4
}
