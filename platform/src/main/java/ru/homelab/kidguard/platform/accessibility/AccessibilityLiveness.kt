package ru.homelab.kidguard.platform.accessibility

import javax.inject.Inject
import javax.inject.Singleton

/**
 * Подключён ли наш accessibility-сервис ПРЯМО СЕЙЧАС, по его собственному слову.
 *
 * Зачем отдельный признак, если есть `Settings.Secure` и системный список привязанных сервисов:
 * оба — внешние источники, и первый уже подводил. Боевой случай (телефон Олега, 31.08.2026):
 * процесс убил вендорский «оптимизатор», система подняла обратно foreground-сервис, а
 * accessibility-сервис оставила в `Crashed services`. Ключи настроек при этом остались «выдано»,
 * то есть снаружи всё выглядело здоровым, а событий не приходило ни одного и не блокировалось
 * ничего — девять часов подряд.
 *
 * Этот флаг такого обмана не допускает по построению: он живёт в памяти процесса и выставляется
 * только самим сервисом в [KidGuardAccessibilityService.onServiceConnected]. Умер процесс — вместе
 * с ним умер и флаг, а поднявшийся заново процесс стартует с `false`, пока сервис в НЁМ не
 * подключится. Если сервис не подключился, значит контроля нет — и это не предположение о
 * поведении прошивки, а факт.
 *
 * Единственный слепой угол — система молча отвязала сервис, не позвав `onUnbind`/`onDestroy`;
 * его закрывает вторая проверка, по системному списку (см. `PermissionsManager`).
 */
@Singleton
class AccessibilityLiveness @Inject constructor() {

    /** Пишется из главного потока сервиса, читается из корутины сторожа — отсюда `@Volatile`. */
    @Volatile
    var connected: Boolean = false
        private set

    fun onConnected() {
        connected = true
    }

    fun onDisconnected() {
        connected = false
    }
}
