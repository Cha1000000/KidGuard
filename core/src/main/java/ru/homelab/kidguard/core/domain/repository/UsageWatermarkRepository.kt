package ru.homelab.kidguard.core.domain.repository

import java.time.Instant

/**
 * Ватерлиния учёта: момент, до которого экранное время посчитано достоверно.
 *
 * Двигается на каждом тике живого учёта. Разрыв между ней и «сейчас» — это ровно тот промежуток,
 * когда контроль не работал (его убили, телефон перезагружался, приложение не успело стартовать),
 * и именно его закрывает досчёт по системной статистике.
 *
 * Хранится отдельно от настроек: это не пользовательский выбор, а служебное состояние движка
 * учёта, и живёт оно по своим правилам (пишется часто, сбрасывается вместе с данными учёта).
 */
interface UsageWatermarkRepository {

    /** До какого момента учёт достоверен; `null` — учёт ещё ни разу не работал. */
    suspend fun accountedUntil(): Instant?

    /** Сдвинуть ватерлинию. Вызывается и живым тиком, и досчётом после того, как он всё записал. */
    suspend fun setAccountedUntil(moment: Instant)
}
