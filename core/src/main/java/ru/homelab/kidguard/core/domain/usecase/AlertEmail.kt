package ru.homelab.kidguard.core.domain.usecase

/**
 * Проверка адреса для писем-тревог перед отправкой на сервер.
 *
 * Намеренно грубая — непустое имя, одна собака, домен с точкой, без пробелов. Ровно та же
 * проверка стоит на сервере (`alertEmailService.isValidEmail`), и обе решают одну задачу:
 * отсечь очевидный мусор, чтобы кнопка «Сохранить» не отправляла заведомо бесполезный запрос.
 * Доставляемость адреса этим не проверяется вовсе — её подтверждает только проверочное письмо.
 *
 * Строгая RFC-совместимая регулярка здесь была бы хуже: она длинная, её никто не читает, и она
 * отвергает валидные адреса, которых мы даже не предвидели.
 *
 * Живёт в `:core`, а не в `:app`, потому что `android.util.Patterns` недоступен в unit-тестах
 * (в JVM-варианте android.jar все методы бросают исключение) — а проверка должна быть покрыта.
 */
private val EMAIL_PATTERN = Regex("""^[^\s@]+@[^\s@]+\.[^\s@]+$""")

fun isValidAlertEmail(raw: String): Boolean = EMAIL_PATTERN.matches(raw.trim())

/**
 * Нормализует введённое: обрезает пробелы, пустую строку превращает в `null`.
 *
 * `null` — «слать на адрес аккаунта». Пустое поле на экране означает ровно это, поэтому очистка
 * поля крестиком и есть сброс: заставлять родителя вручную вписывать свой же гугловский адрес,
 * чтобы вернуться к исходному поведению, было бы издевательством.
 */
fun normalizeAlertEmail(raw: String): String? = raw.trim().ifEmpty { null }
