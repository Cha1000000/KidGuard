package ru.homelab.kidguard.core.domain.repository

import ru.homelab.kidguard.core.domain.model.AlertEmailSaved
import ru.homelab.kidguard.core.domain.model.AlertSettings

/**
 * Настройки оповещений родителя (экран «Оповещения»): каким каналом звать по каждому ребёнку и на
 * какой адрес слать письма.
 *
 * Это подписка ИМЕННО ЭТОГО родителя, а не свойство ребёнка: у ребёнка бывает двое равноправных
 * родителей, и правила у них общие, а подписка на тревоги — личная. Поэтому настройки не лежат в
 * политике и не едут в [PolicyRepository].
 */
interface AlertSettingsRepository {

    /** Загрузить состояние экрана целиком. `Result.failure` — нет сети или сервер недоступен. */
    suspend fun load(): Result<AlertSettings>

    /**
     * Переключить каналы для одного ребёнка. Незаданный канал остаётся как был — экран умеет
     * менять по одной галке.
     */
    suspend fun setChildPrefs(childId: Int, push: Boolean? = null, email: Boolean? = null): Result<Unit>

    /**
     * Сменить адрес для писем. `null` — вернуться на адрес аккаунта.
     *
     * В [AlertEmailSaved] едет признак, ушло ли на новый адрес проверочное письмо: сервер
     * сохраняет адрес даже когда отправка не удалась, и экран не должен обещать письмо, которого
     * не было.
     */
    suspend fun setAlertEmail(email: String?): Result<AlertEmailSaved>

    /**
     * Показывать ли уведомление в шторку об этом ребёнке. Читается из локального кэша, который
     * обновляется при каждой успешной загрузке и записи, — потому что спрашивают об этом из
     * фоновой проверки здоровья, где лишний сетевой запрос был бы и медленным, и ненадёжным.
     *
     * Неизвестный ребёнок (кэш пуст, сервер старый) — `true`: прежнее поведение, тревога важнее
     * аккуратности.
     */
    suspend fun pushEnabled(childId: Int): Boolean
}
