package ru.homelab.kidguard.core.domain.model

/**
 * Причина, по которой конкретному приложению закрыт доступ.
 *
 * Отдельная от «что показать на экране»: у одного приложения причин может быть несколько
 * одновременно (например, идёт «Время учёбы» И исчерпан общий дневной лимит), а экран показывает
 * одну, приоритетную. Разделение нужно ещё и потому, что экран-замок снимают по причине: пока
 * причина жива, плашка должна висеть, и исчезает она только когда ни одной причины не осталось.
 *
 * Каждая причина называет свой предмет — лимит конкретного приложения или общий, окно расписания,
 * запрет родителя. Благодаря этому «жива ли причина» проверяется предметно, а не флажками.
 */
sealed interface BlockCause {

    /** Идёт «Время учёбы» по расписанию родителя. */
    data object StudyTime : BlockCause

    /** Приложение полностью запрещено родителем (веха 4.1.2). */
    data object BlockedByParent : BlockCause

    /** Исчерпан общий дневной лимит телефона. */
    data object DailyLimitExpired : BlockCause

    /** Исчерпан личный лимит времени конкретного приложения. */
    data class PersonalLimitExpired(val packageName: String) : BlockCause
}
