package ru.homelab.kidguard.core.domain.repository

import kotlinx.coroutines.flow.Flow
import java.time.LocalDateTime

/**
 * Общая временная шкала приложения: тики на границах минут.
 *
 * Расписание — единственное, что меняется само по себе, от хода часов. Поэтому все, кому нужно
 * «что сейчас по расписанию» или «сколько минут до следующего окна», обязаны брать время отсюда:
 * свой тик у каждого потребителя — это рассинхрон (окно срабатывает у одного на минуту раньше, чем
 * у другого) и лишние пробуждения.
 *
 * Реализация — [SharedScheduleTimeline]: тик ровно на границе минуты через [ScheduleClock].
 */
interface ScheduleTimeline {

    /** Тики времени: каждый следующий — на границе следующей минуты. */
    val ticks: Flow<LocalDateTime>
}
