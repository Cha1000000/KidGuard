package ru.homelab.kidguard.core.domain.usecase

/**
 * Итог одной периодической сверки монитора переднего плана со стеком окон.
 *
 * @param accept пакет, который надо записать в монитор, либо `null` — монитор не трогаем.
 * @param candidate расхождение, увиденное этой сверкой и ждущее подтверждения следующей.
 */
data class StackSyncStep(val accept: String?, val candidate: String?)

/**
 * Решает, поправить ли монитор переднего плана по свежему чтению стека окон.
 *
 * Зачем сверка вообще нужна: монитор живёт на событиях окон, а они ненадёжны. Опоздавшее событие
 * лаунчера перезаписывает приложение, которое уже снова на экране, а приложение, которым просто
 * пользуются, новых событий смены окна не шлёт — монитор залипает сколько угодно. Так запрещённое
 * приложение оставалось открытым без блокировки (воспроизведено на эмуляторе 17.09.2026), а время
 * писалось не на то приложение.
 *
 * Почему не верим одному чтению: стек окон у сервиса доступности сам запаздывает (после поворота
 * экрана он показывал игру, хотя на экране был лаунчер). Одно чтение поправило бы верный монитор
 * устаревшим значением и мигнуло бы блокировкой на рабочем столе. Поэтому расхождение принимаем,
 * только когда ДВЕ сверки подряд увидели один и тот же пакет.
 *
 * @param current что сейчас в мониторе.
 * @param observed верхнее прикладное окно по стеку; `null` — прикладных окон нет или стек не прочитан.
 * @param candidate расхождение, увиденное предыдущей сверкой.
 */
fun nextStackSync(current: String?, observed: String?, candidate: String?): StackSyncStep = when {
    // Экран блокировки, AOD или сбой чтения: судить не по чему, и цепочку подтверждения рвём —
    // «два чтения подряд» должны быть действительно подряд.
    observed == null -> StackSyncStep(accept = null, candidate = null)
    observed == current -> StackSyncStep(accept = null, candidate = null)
    observed == candidate -> StackSyncStep(accept = observed, candidate = null)
    else -> StackSyncStep(accept = null, candidate = observed)
}

/**
 * Повторить ли блокировку приложения, которое уже было заблокировано.
 *
 * Блокировка срабатывала один раз — на смене решения. Если переход «приложение → рабочий стол →
 * приложение» терялся (быстрые значения склеились, или событие рабочего стола на HiOS не пришло),
 * решение не менялось, оверлей уходил сам через несколько секунд, а приложение оставалось открытым.
 * Поэтому, пока решение «блокировать», контроллер периодически спрашивает эту функцию.
 *
 * Повторяем, только когда ребёнок действительно в заблокированном приложении, и подтверждаем это
 * ДВУМЯ источниками: монитором и свежим чтением стека окон. Монитор врёт в обе стороны — на HiOS
 * он остаётся на приложении, когда ребёнок уже на рабочем столе, и повтор по одному монитору
 * накрывал бы рабочий стол оверлеем.
 *
 * @param blockedPackage приложение, на которое принято действующее решение «блокировать».
 * @param currentPackage что сейчас в мониторе переднего плана.
 * @param onScreenPackage верхнее прикладное окно по свежему чтению стека; `null` — не прочитано.
 * @param blockingUiVisible показан ли наш блокирующий UI (оверлей, замок, PIN-экран). Пока он
 * на экране, повторять нечего, а PIN-экран означает, что родитель вводит PIN обхода — мешать нельзя.
 */
fun shouldRepeatBlock(
    blockedPackage: String,
    currentPackage: String?,
    onScreenPackage: String?,
    blockingUiVisible: Boolean
): Boolean = !blockingUiVisible && currentPackage == blockedPackage && onScreenPackage == blockedPackage

/**
 * Видимые, но не активные приложения, которые стоит проверить на блокировку.
 *
 * Активное проверяет основной путь контроллера; лаунчер и сам KidGuard не блокируются никогда
 * ([alwaysAllowed]); пакет, открытый родителем по PIN ([bypassedPackage]), не трогаем, пока обход действует.
 */
fun backgroundVisibleCandidates(
    visible: Set<String>,
    activePackage: String?,
    alwaysAllowed: Set<String>,
    bypassedPackage: String?
): Set<String> = visible.filterTo(mutableSetOf()) {
    it != activePackage && it !in alwaysAllowed && it != bypassedPackage
}

/**
 * Блокировать видимое окно — только если его видели запрещённым ДВЕ проверки подряд.
 *
 * Стек окон отстаёт от экрана: окно приложения, из которого только что ушли, ещё мгновение числится
 * видимым. Одна проверка накрыла бы оверлеем экран, на котором этого приложения уже нет.
 */
fun confirmedAcrossChecks(previous: Set<String>, current: Set<String>): Set<String> = current intersect previous
