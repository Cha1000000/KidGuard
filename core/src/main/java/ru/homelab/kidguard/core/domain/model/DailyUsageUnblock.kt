package ru.homelab.kidguard.core.domain.model

import java.time.LocalDate

/**
 * Маркер разблокировки дня: родитель снимает свою же блокировку ([DailyUsageBlock]).
 *
 * Отдельный маркер, а не удаление блокировки из политики: ребёнку нужно отличить «разблокировали»
 * от «блокировки и не было», а удалённое поле такого различия не несёт. Идемпотентен по [issuedAt],
 * как остальные маркеры дня.
 *
 * [restoreRemaining] различает два способа снять блокировку:
 * - `true` — кнопка «Разблокировать»: ребёнку возвращается ровно то время, что оставалось у него
 *   до блокировки;
 * - `false` — родитель выдал бонус телефона во время блокировки. Бонус сам даёт ребёнку время, а
 *   остаток до блокировки при этом не возвращается (решение Володи 15.09.2026). Маркер нужен
 *   потому, что у бонуса нет метки времени и по нему нельзя понять, выдан он до блокировки или
 *   после, — без маркера статус «заблокировано» у родителя остался бы висеть.
 */
data class DailyUsageUnblock(
    val date: LocalDate,
    val issuedAt: Long,
    val restoreRemaining: Boolean
)

/**
 * Пора ли применить разблокировку на телефоне ребёнка.
 *
 * Помимо обычных условий маркера дня (сегодняшний, новее применённого) разблокировка обязана быть
 * **новее блокировки**. В политике хранится по одному маркеру каждого типа, и последовательность
 * «заблокировал → разблокировал → снова заблокировал» оставляет в документе старую разблокировку
 * рядом с новой блокировкой. Применить её значило бы молча снять свежую блокировку.
 */
fun shouldApplyUnblock(
    marker: DailyUsageUnblock?,
    block: DailyUsageBlock?,
    today: LocalDate,
    lastAppliedAt: Long
): Boolean {
    if (marker == null || marker.date != today || marker.issuedAt <= lastAppliedAt) return false
    val todayBlock = block?.takeIf { it.date == today } ?: return false
    return marker.issuedAt > todayBlock.issuedAt
}
