package ru.homelab.kidguard.core.domain.model

import java.time.LocalDate

/**
 * Назначенный родителем штраф — время, снятое с дневного лимита за день (план
 * `daily-limit-penalty.md`). Обратная операция к [BonusGrant]: тот прибавляет время, этот
 * вычитает.
 *
 * [minutes] — **положительное** число снятых минут. Знак живёт в формуле бюджета
 * ([dayBudgetMinutes]), а не в данных: отрицательные значения в БД слишком легко случайно
 * сложить с бонусом и получить бессмысленный результат.
 *
 * [packageName] = "" — штраф на весь телефон (тот же маркер, что в Room-таблице
 * `penalty_grants` и у бонусов). Сейчас используется только он: штрафов для отдельных
 * приложений нет. Поле заведено сразу, потому что входит в составной первичный ключ, и
 * добавить его позже можно было бы только пересозданием таблицы.
 *
 * [comment] — пояснение родителя «за что», которое ребёнок видит на экране «Сегодня». Пустая
 * строка, а не `null`: «комментария не было» и «комментарий стёрли» — одно и то же состояние.
 */
data class PenaltyGrant(
    val date: LocalDate,
    val packageName: String,
    val minutes: Int,
    val comment: String = ""
)
