package ru.homelab.kidguard.core.domain.usecase

/**
 * Снимать ли PIN-оверлей по событию окна другого приложения.
 *
 * Для обычных критичных экранов (настройки, VPN, «О приложении») — прежнее правило: оверлей уходит,
 * когда пользователь ушёл с хоста — событие пришло от пакета, которого нет среди [hostPackages].
 *
 * **PIN над списком последних ([overlayForRecents]) по событиям окон не снимается никогда.** Раньше
 * снимался, и это был путь, которым ребёнок останавливал контроль (15.09.2026, телефон Олега):
 * - при входе в обзор из горизонтальной игры экран поворачивается в портрет, пересоздаются окна
 *   systemui (панель навигации, строка состояния), шлёт событие сама игра — и правило принимало
 *   это за «ушёл в другое приложение», убирая замок через секунду;
 * - панель «Меню спец. возможностей» с действием «Недавние приложения» — тоже окно systemui.
 *
 * Отличить настоящий уход от этих событий по списку окон нельзя: у сервиса доступности он
 * запаздывает и после поворота показывал игру. Поэтому PIN обзора уходит только по решению
 * человека (верный PIN или отказ) либо по звонку — см. [shouldDismissRecentsPinOnCall].
 *
 * @param eventPackage пакет окна, приславшего событие.
 * @param ownPackage пакет самого KidGuard — события собственного оверлея не должны его снимать.
 */
fun shouldDismissPinOverlayOnWindowEvent(
    overlayForRecents: Boolean,
    eventPackage: String,
    ownPackage: String,
    hostPackages: Set<String>
): Boolean {
    if (eventPackage == ownPackage) return false
    if (overlayForRecents) return false
    return eventPackage !in hostPackages
}

/**
 * Снимать ли PIN над списком последних из-за звонка — единственное внешнее исключение из правила
 * выше. Звонок нельзя закрывать замком: ребёнок должен иметь возможность ответить. Входящий
 * вызов перекрывает обзор, поэтому снятие замка ничего не открывает; после звонка обзор, если он
 * снова показан, перехватится заново.
 */
fun shouldDismissRecentsPinOnCall(overlayForRecents: Boolean, callActive: Boolean): Boolean =
    overlayForRecents && callActive
