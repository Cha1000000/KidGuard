package ru.homelab.kidguard.core.domain.usecase

/**
 * «Пропуск» приложения сверх исчерпанного общего дневного лимита: родитель выдал конкретному
 * приложению дополнительное время, чтобы ребёнок мог им воспользоваться, пока телефон в целом
 * заблокирован (типовой случай — срочно написать или позвонить в мессенджере).
 *
 * Пропуск тратится **временем в самом приложении**, а не по настенным часам: выданные минуты не
 * утекают, пока ребёнок приложением не пользуется. Поэтому родитель может выдать время и заранее,
 * а ребёнок — выйти ответить на звонок, не потеряв остаток.
 *
 * Счётчик расхода ведётся отдельно от расхода личного лимита ([bonusSpentSeconds]) и растёт
 * только когда общий дневной лимит уже исчерпан — см. [usageTickTargets].
 */
fun hasBonusAccessPass(bonusMinutes: Int, bonusSpentSeconds: Int): Boolean =
    bonusMinutesLeft(bonusMinutes, bonusSpentSeconds) > 0

/**
 * Сколько минут пропуска осталось. Никогда не отрицательный: расход снимается тиками и между
 * ними может перевалить за выданное — «минус три минуты» родителю показывать незачем.
 *
 * Расход округляется вниз до минуты, поэтому неполная минута пропуск не гасит: выдав 15 минут,
 * родитель отдаёт именно 15, а не 14 с хвостом.
 */
fun bonusMinutesLeft(bonusMinutes: Int, bonusSpentSeconds: Int): Int =
    (bonusMinutes - bonusSpentSeconds / 60).coerceAtLeast(0)
