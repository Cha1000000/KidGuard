package ru.homelab.kidguard.core.domain.model

/**
 * Специальные разрешения детского режима, выдаваемые вручную через системные экраны.
 * Порядок объявления = порядок шагов в мастере первичной настройки.
 */
enum class DevicePermission {
    /** Accessibility-сервис (детект активного приложения, оверлей-блокировка). */
    ACCESSIBILITY,

    /** Рисование поверх других приложений (экраны блокировки и предупреждений). */
    OVERLAY,

    /** Администратор устройства (защита от удаления; НЕ Device Owner). */
    DEVICE_ADMIN,

    /** Исключение из оптимизации батареи (чтобы фоновый контроль не выгружался). */
    BATTERY_OPTIMIZATION,

    /** Показ уведомлений (чтобы было видно уведомление активного контроля). */
    NOTIFICATIONS,

    /** Согласие на VPN (блокировка интернета после лимита; полноценно — веха 5). */
    VPN,

    /**
     * Доступ к системной статистике использования (`PACKAGE_USAGE_STATS`).
     *
     * Нужен, чтобы досчитать время, пройденное мимо нашего учёта, пока контроль был убит. Ценен
     * тем, что этот доступ, в отличие от accessibility, **переживает force-stop**: система ведёт
     * статистику сама, и после того как приложение подняли руками, провал можно закрыть задним
     * числом. Без него всё продолжает работать, просто убить контроль снова становится выгодно —
     * поэтому в [DeviceHealth] он не входит.
     */
    USAGE_ACCESS,

    /**
     * Звонок экстренному контакту прямо с ночного замка «Времени сна».
     *
     * Единственное runtime-разрешение в списке (остальные выдаются через системные экраны) и
     * единственное необязательное: без него кнопка на замке открывает телефон с набранным
     * номером вместо прямого вызова. Поэтому в [DeviceHealth] оно не входит — контроль без
     * него полноценен.
     */
    EMERGENCY_CALL
}
