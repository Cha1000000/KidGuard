package ru.homelab.kidguard.core.domain.usecase

import java.time.Instant
import java.time.LocalTime
import java.time.ZoneId

/**
 * Ночные часы, когда родителя не тревожим (решение Володи 01.09.2026).
 *
 * Зачем понадобилось: порог молчания снижен с 12 часов до 40 минут ([ru.homelab.kidguard.core
 * .domain.model.Child.STALE_AFTER]), а телефон ребёнка ночью выключен или без сети — это норма.
 * Без ночного окна родитель получал бы тревогу каждую ночь, и через неделю перестал бы их читать.
 *
 * Тревогу в это время не показываем и снимок состояния не обновляем: тогда утром сравнение
 * «было в порядке → сломалось» сработает как обычно, и родитель увидит одно уведомление вместо
 * ночной серии. Отдельного «отложенного» хранилища для этого не нужно.
 *
 * Окно фиксированное, а не из расписания сна: расписание у родителя лежит только для активного
 * ребёнка, а проверка идёт сразу по всем — привязка к нему давала бы разное поведение для разных
 * детей без всякой на то причины.
 */
fun isQuietHours(now: Instant, zone: ZoneId = ZoneId.systemDefault()): Boolean {
    val time = now.atZone(zone).toLocalTime()
    // Окно переходит через полночь, поэтому это ИЛИ, а не диапазон.
    return time >= QUIET_FROM || time < QUIET_UNTIL
}

/** С 23:00 родителя не беспокоим. */
private val QUIET_FROM: LocalTime = LocalTime.of(23, 0)

/** В 8 утра тревоги снова доходят — и накопившееся молчание показывается одним уведомлением. */
private val QUIET_UNTIL: LocalTime = LocalTime.of(8, 0)
