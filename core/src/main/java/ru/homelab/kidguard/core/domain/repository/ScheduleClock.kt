package ru.homelab.kidguard.core.domain.repository

import java.time.LocalDateTime

/**
 * Часы и ожидание границы минуты для расписания. Вынесены из use case, чтобы:
 * - тик был ровно по минуте, а не «раз в 30 секунд» (границы окон минутные);
 * - поведение проверялось JVM-тестом без Android и реального ожидания.
 */
interface ScheduleClock {

    /** Текущее локальное время (в зоне устройства). */
    fun now(): LocalDateTime

    /**
     * Дождаться следующей границы минуты. После возврата [now] уже принадлежит новой минуте;
     * на ровной границе ждём полную минуту, чтобы не крутиться в нулевом цикле.
     */
    suspend fun awaitNextMinute()
}
