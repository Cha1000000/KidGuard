package ru.homelab.kidguard.core.domain.usecase

/**
 * Значок замка на карточке в списке последних: по нему видно, закреплена ли карточка KidGuard.
 *
 * Закрепление — единственная защита от кнопки «Очистить всё», которая работает всегда: PIN-замок
 * система прячет на время поворота экрана, и в эту щель ребёнок успевает нажать кнопку (телефон
 * Олега, 18.09.2026). Состояние закрепления наружу не отдаётся ни одним API, зато у закреплённой
 * карточки появляется значок — его и ищем, пока список последних всё равно перед глазами сервиса.
 *
 * Имена значка у оболочек разные; на HiOS это `taskLockIconTop`. Если ни одного не нашли, вывод —
 * «не знаем» (на этой оболочке закрепления может не быть вовсе), и родителя мы не тревожим.
 */
private val LOCK_ICON_ID_NAMES = listOf("taskLockIconTop", "taskLockIcon", "task_lock_icon", "task_lock")

/** Полные id значка замка для пакета лаунчера. */
fun recentsLockIconIdsFor(launcherPackage: String): List<String> =
    LOCK_ICON_ID_NAMES.map { "$launcherPackage:id/$it" }
