package ru.homelab.kidguard.core.domain.usecase

/**
 * Род окна на экране — ровно те категории, которые различает выбор переднего плана.
 *
 * Платформенные константы (`AccessibilityWindowInfo.TYPE_*`) сюда не проникают намеренно: правило
 * «что считать приложением» — доменное, и проверяться должно без Android.
 */
enum class WindowKind {

    /** Окно обычного приложения (активность, её диалог, всплывающее меню). */
    APPLICATION,

    /** Окно системной оболочки: шторка уведомлений, панель громкости, навбар, AOD. */
    SYSTEM,

    /** Клавиатура. */
    INPUT_METHOD,

    /** Оверлей — в том числе наши собственные блокирующие экраны. */
    OVERLAY,

    /** Всё остальное: разделитель split-screen, окно увеличения и прочая служебная мелочь. */
    OTHER
}

/**
 * Снимок одного окна: чем оно является, насколько высоко лежит и какому пакету принадлежит.
 * [packageName] == null означает «пакет неизвестен» (содержимое окна ещё не доехало) — такое окно
 * в выборе переднего плана не участвует.
 */
data class WindowSnapshot(
    val id: Int,
    val kind: WindowKind,
    val layer: Int,
    val packageName: String?
)

/**
 * Какое приложение сейчас на переднем плане — верхнее ПРИКЛАДНОЕ окно, а не просто верхнее.
 *
 * Разбор боевого случая (телефон Олега, 06.09.2026): учёт приписывал системной оболочке треть
 * экранного времени — 51 минуту за сутки и 459 минут за неделю, при том что система за те же
 * сутки давала `com.android.systemui` ровно `totalTimeUsed="00:00"` и `appLaunchCount=0`.
 * Причина: активное приложение брали из `event.packageName` любого события смены окна, а такие
 * события шлёт КАЖДОЕ окно — шторка уведомлений, панель громкости, навбар, always-on display,
 * клавиатура, тост. Одно движение пальцем по шторке подменяло собой приложение, и значение
 * залипало до следующего события.
 *
 * Цена ошибки была не только в кривой статистике: личные лимиты приложений отсчитывались в
 * полтора раза дольше (треть времени не писалась на приложение), а залипание поверх лаунчера или
 * приложения из белого списка тратило дневной лимит, которого тратить не должно.
 *
 * `null` — прикладных окон на экране нет (экран блокировки, AOD). Вызывающий на это НЕ обнуляет
 * последнее известное приложение: пустой ответ бывает и в момент переключения между экранами, а
 * сброшенный передний план на мгновение снял бы блокировку — см. вызов в accessibility-сервисе.
 */
fun resolveForegroundPackage(windows: List<WindowSnapshot>): String? = windows
    .filter { it.kind == WindowKind.APPLICATION && !it.packageName.isNullOrBlank() }
    .maxByOrNull { it.layer }
    ?.packageName
