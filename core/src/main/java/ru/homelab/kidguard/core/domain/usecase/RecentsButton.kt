package ru.homelab.kidguard.core.domain.usecase

/**
 * Подписи кнопки «Обзор» на панели навигации — по ним нажатие узнаётся раньше, чем открывается сам обзор.
 *
 * Зачем: система сообщает об открытии списка последних только к концу анимации — 0,45–0,65 с после жеста,
 * а при повороте экрана (обзор из горизонтальной игры) и того позже. Ребёнок успевал нажать «Очистить всё»
 * до появления замка (телефон Олега, 17.09.2026, воспроизведено дважды подряд). Нажатие по кнопке
 * панели навигации приходит отдельным событием в момент касания — это самый ранний доступный сигнал.
 *
 * Подписи берём и русские, и английские: язык оболочки у разных семей разный.
 */
private val RECENTS_BUTTON_LABELS = listOf("просмотр", "обзор", "недавние", "последние", "recent", "overview", "app switch")

/**
 * Похоже ли нажатие на кнопку «Обзор»: событие пришло от системной оболочки, а подпись элемента совпала.
 *
 * Пакет оболочки проверяем обязательно — иначе кнопка с подписью «Обзор» внутри любого приложения
 * (например, в магазине) поднимала бы PIN-замок.
 */
fun isRecentsButtonClick(eventPackage: String?, shellPackages: Set<String>, label: String?): Boolean {
    if (eventPackage == null || eventPackage !in shellPackages) return false
    val normalized = label?.lowercase()?.trim().orEmpty()
    if (normalized.isEmpty()) return false
    return RECENTS_BUTTON_LABELS.any { normalized.contains(it) }
}
