package ru.homelab.kidguard.core.domain.repository

import ru.homelab.kidguard.core.domain.usecase.RawUsageEvent
import java.time.Instant

/**
 * Системная статистика использования — второй, независимый от нашего accessibility-сервиса,
 * источник правды о том, чем пользовались на телефоне.
 *
 * Нужен ровно для одного: закрыть провал в учёте, пока контроль был мёртв. Его ценность в том,
 * что доступ к этой статистике переживает force-stop, а accessibility — нет.
 */
interface UsageEventSource {

    /** Доступ выдан (тумблер «Доступ к данным использования»). Без него [events] вернёт пусто. */
    fun isAvailable(): Boolean

    /**
     * События в окне [from]..[to].
     *
     * Возвращает и событие, открывшее окно раньше [from], если приложение было на переднем плане
     * ещё до его начала: без него провал, случившийся посреди игры, оказался бы недосчитан.
     * Пустой список — доступа нет либо система ничего не отдала; вызывающий трактует это как
     * «досчитывать нечего», а не как «телефоном не пользовались».
     */
    fun events(from: Instant, to: Instant): List<RawUsageEvent>
}
